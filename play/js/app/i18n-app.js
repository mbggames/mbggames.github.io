  function t(lang, key, params) {
    var table = STRINGS[lang] || STRINGS.en;
    var v = table[key];
    if (v === undefined) v = STRINGS.en[key];
    if (v === undefined) return key;
    return typeof v === 'function' ? v(params || {}) : v;
  }

  /** Language names, always written in the language itself, and the languages in menu order. */
  var LANGS = ['en', 'sq', 'bs', 'de', 'es', 'fr', 'tr', 'pl', 'pt', 'ar'];
  var NAMES = { en: 'English', sq: 'Shqip', bs: 'Bosanski', de: 'Deutsch', es: 'Español', fr: 'Français', tr: 'Türkçe',
    pl: 'Polski', pt: 'Português', ar: 'العربية' };
  /** Languages written from right to left. */
  var RTL = ['ar'];

  /**
   * Thousands separator: 40,000 (en, sq, ar - Western digits, as on most Arabic phones) ·
   * 40.000 (bs, de, es, tr, pt) · 40 000 (fr, pl).
   */
  var GROUP = { en: ',', sq: ',', bs: '.', de: '.', es: '.', fr: '\u00a0', tr: '.', pl: '\u00a0', pt: '.', ar: ',' };
  function num(lang, n) {
    var s = String(Math.round(Number(n) || 0));
    var neg = s.charAt(0) === '-';
    if (neg) s = s.slice(1);
    s = s.replace(/\B(?=(\d{3})+(?!\d))/g, GROUP[lang] || ',');
    return (neg ? '-' : '') + s;
  }

  /** Decimal numbers (average tries): 4.2 (en, ar) · 4,2 (all others). */
  function dec(lang, n, digits) {
    var s = (Math.round((Number(n) || 0) * Math.pow(10, digits == null ? 1 : digits)) / Math.pow(10, digits == null ? 1 : digits)).toFixed(digits == null ? 1 : digits);
    return lang === 'en' || lang === 'ar' ? s : s.replace('.', ',');
  }

